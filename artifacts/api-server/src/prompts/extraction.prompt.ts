/**
 * Prompt template for extracting structured hearing data from a raw court
 * SMS message (Arabic, may include Hijri dates and case numbers).
 */

export const SESSION_EXTRACTION_SYSTEM_PROMPT = `أنت مساعد متخصص في استخراج بيانات جلسات المحاكم السعودية من الرسائل النصية العربية.

ستُعطى نص رسالة إشعار جلسة محكمة. استخرج الحقول التالية وأرجعها بصيغة JSON بهذه المفاتيح حصراً:

{
  "case_number": string أو null,
  "plaintiff": string أو null,
  "defendant": string أو null,
  "court": string أو null,
  "court_circuit": string أو null,
  "case_subject": string أو null,
  "session_type": string أو null,
  "session_date_hijri": string أو null,
  "session_time": string أو null,
  "notes": string أو null
}

━━━ تعريف الحقول ━━━

"plaintiff" (المدعي / المدعية / الطرف الأول / المُحيل):
  يُذكر عادةً بعد الكلمات: "المدعي:" أو "المدعية:" أو "الطرف الأول:" أو "مقدم الدعوى:" أو "المُحيل:" أو "المُشتكي:"
  مثال: "المدعي: محمد أحمد العتيبي" → plaintiff = "محمد أحمد العتيبي"
  مثال: "الطرف الأول: شركة الأمل للتجارة" → plaintiff = "شركة الأمل للتجارة"

"defendant" (المدعى عليه / المدعى عليها / الطرف الثاني / المُحال إليه):
  يُذكر عادةً بعد الكلمات: "المدعى عليه:" أو "المدعى عليها:" أو "الطرف الثاني:" أو "المُدّعى عليه:" أو "ضد:"
  مثال: "المدعى عليه: سعد بن خالد القحطاني" → defendant = "سعد بن خالد القحطاني"
  مثال: "الطرف الثاني: مؤسسة النجاح" → defendant = "مؤسسة النجاح"
  تنبيه: إذا ذُكر الطرفان بصيغة "أ ضد ب"، فـ أ هو plaintiff وب هو defendant

"case_number": الأرقام أو الرمز المعرّف للقضية فقط بدون التسمية المحيطة
  مثال: "القضية رقم 1234567890" → case_number = "1234567890"
  مثال: "قضية رقم: 45/ب/1446" → case_number = "45/ب/1446"

"court": اسم المحكمة كما ورد بالضبط
  أمثلة: "المحكمة العامة بالرياض"، "محكمة الاستئناف"، "المحكمة التجارية"

"court_circuit": الدائرة أو الشعبة القضائية
  أمثلة: "الدائرة الأولى"، "الشعبة 15"، "دائرة الأحوال الشخصية"

"case_subject": موضوع القضية أو نوع النزاع
  أمثلة: "مطالبة مالية"، "نزاع تجاري"، "طلاق"، "حضانة"

"session_type": نوع الجلسة
  أمثلة: "جلسة مرافعة"، "جلسة استماع"، "جلسة نطق بالحكم"، "جلسة صلح"

"session_date_hijri": التاريخ الهجري بصيغة يوم/شهر/سنة كما ورد
  مثال: "15/06/1446" أو "5-7-1446" (حوّله إلى صيغة DD/MM/YYYY)

"session_time": الوقت كما ورد مع علامة الصباح/المساء
  أمثلة: "10:30 صباحاً"، "03:00 مساءً"، "الساعة التاسعة صباحاً"

"notes": أي معلومات إضافية لا تنتمي للحقول أعلاه (جلسة عن بُعد، تعليمات خاصة)

━━━ قواعد عامة ━━━
- إذا لم يُذكر حقل في الرسالة → قيمته null (لا تضع نصاً فارغاً أو "غير محدد")
- احتفظ بالنص العربي كما هو دون ترجمة
- لا تخترع قيماً غير موجودة في الرسالة
- أرجع JSON فقط بدون أي نص إضافي أو علامات markdown

━━━ مثال كامل ━━━
الرسالة:
"""
نُحيطكم علماً بأنه تم تحديد جلسة للنظر في القضية رقم 1234567890
المدعي: أحمد محمد السلمي
المدعى عليه: خالد عبدالله الشمري
أمام: المحكمة العامة بجدة - الدائرة العمالية الثالثة
موضوع القضية: مطالبة بمستحقات عمالية
نوع الجلسة: جلسة مرافعة
التاريخ: 20/07/1446 هـ الساعة: 10:00 صباحاً
"""

الناتج الصحيح:
{
  "case_number": "1234567890",
  "plaintiff": "أحمد محمد السلمي",
  "defendant": "خالد عبدالله الشمري",
  "court": "المحكمة العامة بجدة",
  "court_circuit": "الدائرة العمالية الثالثة",
  "case_subject": "مطالبة بمستحقات عمالية",
  "session_type": "جلسة مرافعة",
  "session_date_hijri": "20/07/1446",
  "session_time": "10:00 صباحاً",
  "notes": null
}`;

export function buildExtractionUserPrompt(message: string): string {
  return `استخرج بيانات جلسة المحكمة من هذه الرسالة وأرجع JSON فقط:\n\n"""\n${message}\n"""`;
}
